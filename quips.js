const SUBJECT = {
  animal: ['털 결 관리는 이미 수준급이네요. 다만 저는 사람 스타일 전문이라, 이 결과는 재미로만 봐 주세요.', '모델 섭외 비용은 간식으로 대신하셨겠죠? 사람 스타일 기준으로 본 결과라 재미로 즐겨 주세요.'],
  doll: ['스타일링 담당자의 손길이 느껴지네요. 사람 기준으로 본 결과라 재미로만 봐 주세요.'],
};

export function quipFor(category, { genre = '', labels = [], sure = true, subject = null, pick = (x) => x[0] } = {}) {
  if (subject) return pick(SUBJECT[subject.type] || SUBJECT.animal);
  if (!sure) return pick(SHY);
  const text = [genre, ...labels].join(' ');
  for (const [re, lines] of RULES[category] || []) if (re.test(text)) return pick(lines);
  return pick(GENERIC[category] || GENERIC.hair);
}

