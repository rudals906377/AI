export function quipFor(category, { genre = '', labels = [], sure = true, subject = null, seed = 0 } = {}) {
  if (subject) return at(SUBJECT[subject.type] || SUBJECT.animal, seed);
  if (!sure) return at(SHY, seed);
  const text = [genre, ...labels].join(' ');
  const rule = (RULES[category] || []).find(([re]) => re.test(text));
  const [wits, tips] = rule ? rule.slice(1) : (GENERIC[category] || GENERIC.hair);
  return `${at(wits, seed)} ${at(tips, Math.floor(seed / wits.length), 1)}`;
}

