export function manyMessage(counts, seed = 0) {
  const people = counts['사람'] || 0;
  const others = Object.keys(counts).filter((k) => k !== '사람');
  const what = ga(Object.entries(counts).map(([k, n]) => `${k} ${n}${unit(k)}`).join(', '));
  let pool = !others.length ? MANY.people : !people ? MANY.animals : MANY.mixed;
  // 종류가 여럿이면 '강아지 여럿이' 처럼 한 종류를 콕 집는 문장은 뺀다
  if (!people && others.length > 1) pool = pool.filter((f) => f.length === 0);
  const t = at(pool, seed);
  return {
    title: typeof t === 'function' ? t(others[0]) : t,
    body: at(WHY, seed, 1)(what),
    ask: at(others.length ? ASK.other : ASK.people, seed, 2),
  };
}

