export function salonSpec(cut, t, { gender = null, hair = {} } = {}) {
  const b = { ...(BASE[cut] || DEFAULT) };
  const notes = [];
  const cheekPop = -((t.foreheadW || 0) + (t.jawW || 0)) / 2;
  // 얼굴 측정값으로 한두 줄 조정
  if (cheekPop >= 0.8) notes.push('광대가 넓은 편 → 얼굴 둘레 층은 광대 바로 아래에서 시작 (광대 위로 짧은 층 금지)');
  if (t.jawSharp >= 0.8 || t.jawW >= 0.8) notes.push('턱이 각진/넓은 편 → 턱선에서 끝나는 일자 기장은 피하고 턱 아래 2cm 이상 또는 위 3cm 이상');
  if (t.chinW <= -0.8) notes.push('턱끝이 뾰족한 편 → 턱 높이에 컬/볼륨 (끝 C컬 또는 안말음)');
  if (t.long >= 0.8) notes.push('얼굴이 긴 편 → 정수리 볼륨 낮게, 옆 볼륨 살리기, 앞머리로 이마 덮기');
  else if (t.long <= -0.8) notes.push('얼굴이 짧은 편 → 정수리 볼륨 2~3cm 세우기, 옆은 납작하게');
  if (t.foreheadW >= 0.8 || t.upper >= 0.8) notes.push('이마가 넓거나 높은 편 → 앞머리/옆머리로 이마 양옆 덮기');
  if (t.upper <= -0.8) notes.push('이마가 짧은 편 → 무거운 앞머리 금지, 시스루 또는 올리기');
  if (t.mid >= 0.8) notes.push('중안부가 긴 편 → 광대 높이에서 끊어지는 층/앞머리 끝');
  if (t.ears === 'out') notes.push('귀가 옆으로 보이는 편 → 귀를 반쯤 덮는 옆머리 기장 유지, 귀 위 바짝 치지 않기');
  // 내 머리카락
  if (hair.curl === 'curly') { b.perm = /매직|생머리/.test(b.perm) ? '곱슬 → 매직 스트레이트 후 ' + b.perm.replace(/매직 스트레이트 또는 /, '') : b.perm + ' (곱슬기 살려 펌 생략 가능)'; }
  if (hair.curl === 'straight' && /펌/.test(b.perm)) notes.push('직모 → 펌 약 지속 시간 짧게, 열펌 권장');
  if (hair.dens === 'thin') notes.push('숱 적음 → 숱 치지 않기, 뿌리 볼륨 펌 고려');
  if (hair.dens === 'thick') notes.push('숱 많음 → 안쪽 숱 20~30% 정리, 끝 질감 처리');
  if (hair.care === 'low') notes.push('손질 간단 선호 → 드라이 1회로 되는 기장/펌으로, 고정 제품 최소');
  const rows = [['기장', b.len], ['레이어', b.layer], ['가르마', b.part], ['펌 · 질감', b.perm], ['홈케어', b.care]].map(([k, v]) => ({ k, v }));
  if (notes.length) rows.push({ k: '이 얼굴 조정', v: notes.join(' / ') });
  const text = [`[시술 지시서] ${cut}`, ...rows.map((r) => `${r.k}: ${r.v}`), '* 사진으로 잰 비율을 바탕으로 한 안내예요. 실제 길이는 디자이너가 체형에 맞춰 조정해 주세요.'].join('\n');
  return { title: cut, rows, notes, text };
}
