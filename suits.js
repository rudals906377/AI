function item(key, label, text, from) {
  const basis = from.filter(Boolean).map((a) => `${a.group_label} ${a.label}`).join(' · ');
  return { key, label, text, basis };
}

const BY_CATEGORY = { hair, makeup, nail, tattoo };

export function suitsFor(r) {
  const fn = BY_CATEGORY[r.category];
  if (!fn || !r.is_beauty) return { items: [] };
  const by = Object.fromEntries(r.attributes.map((a) => [a.group, a]));
  // 확신이 낮은 속성은 근거로 쓰지 않는다
  const A = (g) => (by[g] && by[g].score >= CONFIDENCE.mid && !by[g].all?.[0]?.hidden ? by[g] : null);
  return { items: fn(A).filter((x) => x.text) };
}
