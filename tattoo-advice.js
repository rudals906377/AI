const pick = (by, key) => { const a = by[key]; return a && !a.all?.[0]?.hidden && a.score >= CONFIDENCE.mid ? a.label : null; };
const alt = (by, key) => { const a = by[key]; return a ? a.label : null; };
const fmtH = (h) => (h < 1 ? `${Math.round(h * 60)}분` : Number.isInteger(h) ? `${h}시간` : `${Math.floor(h)}시간 ${Math.round((h % 1) * 60)}분`);

export function tattooCard(r, { skin = null } = {}) {
  if (!r || r.category !== 'tattoo') return null;
  const by = Object.fromEntries((r.attributes || []).map((a) => [a.group, a]));
  const style = pick(by, 'style') || alt(by, 'style'), styleSure = !!pick(by, 'style');
  const size = pick(by, 'size') || alt(by, 'size'), sizeSure = !!pick(by, 'size');
  const place = pick(by, 'placement') || alt(by, 'placement'), placeSure = !!pick(by, 'placement');
  const color = pick(by, 'color') || alt(by, 'color');
  const motifs = (by.subject?.motifs || []).filter((m, i) => i === 0 || m.score >= 0.15).map((m) => m.ko);
  const subject = pick(by, 'subject');

  // 예상 시술 시간 · 회차
  const sz = SIZE[size] || SIZE.스몰, w = STYLE[style]?.w ?? 1;
  const dark = ['블랙워크', '블랙아웃', '풀컬러', '네오트래디셔널', '뉴스쿨', '이레즈미'].includes(style) || ['풀컬러'].includes(color);
  const h = sz.h.map((x) => Math.round(x * w * (dark ? 1.15 : 1) * 2) / 2), ses = sz.s.map((x, i) => Math.max(1, Math.round(x * (w >= 1.3 ? 1.3 : 1))));
  const plan = {
    size, cm: sz.cm, time: h[0] === h[1] ? fmtH(h[0]) : `${fmtH(h[0])} ~ ${fmtH(h[1])}`, sessions: ses[0] === ses[1] ? `${ses[0]}회` : `${ses[0]}~${ses[1]}회`,
    why: `${size || '스몰'} 크기(${sz.cm})${style ? ` × ${style}` : ''} 기준의 일반적인 범위예요. ${sizeSure ? '' : '사진만으로 크기는 어림이라 '}원하는 크기를 cm 로 정하면 작가가 정확히 알려 줘요.`,
  };
  // 부위
  const pl = PLACE[place];
  const placeInfo = place ? { name: place, sure: placeSure, pain: pl?.pain ?? 3, painText: PAIN_TXT[pl?.pain ?? 3], points: pl?.pts || [] } : null;
  // 장르
  const styleInfo = style ? { name: style, sure: styleSure, points: STYLE[style]?.pts || [] } : null;
  // 컬러 + 피부 톤 발색
  let skinNote = null;
  if (skin?.lab) {
    const L = skin.lab[0];
    skinNote = L >= 68 ? '내 얼굴 분석의 피부 톤이 밝은 편이라 파스텔 · 화이트 · 연한 색도 비교적 잘 보이는 피부예요. 다만 연한 색은 세월에 빨리 옅어져요.'
      : L >= 56 ? '내 얼굴 분석의 피부 톤이 중간이라 선명한 원색(레드 · 블루 · 그린)은 잘 보이고, 파스텔 · 옐로 · 화이트는 흐릿해질 수 있어요.'
      : '내 얼굴 분석의 피부 톤이 어두운 편이라 블랙 · 딥 레드 · 딥 블루 · 그린처럼 진한 색이 또렷하고, 파스텔 · 화이트 · 옐로는 거의 안 보일 수 있어요.';
  }
  const colorInfo = { name: color, points: COLOR[color] || [], skinNote: skinNote || (color && color !== '블랙' ? '내 얼굴 분석을 한 번 하면 피부 톤에 맞는 발색 안내가 여기에 붙어요.' : null) };
  // 디자이너 모드 메모
  const pro = [];
  if (style && NEEDLE[style]) pro.push(`니들(참고): ${NEEDLE[style]}`);
  if (place && PRO_PLACE[place]) pro.push(`부위: ${PRO_PLACE[place]}`);
  pro.push(`예상 ${plan.time} · ${plan.sessions} (크기 × 장르 기본값, 스텐실 대 보고 재산정)`);
  if (motifs.length) pro.push(`모티브 레퍼런스: ${motifs.join(' · ')} — 손님 레퍼런스 그대로 복제하지 않고 재작업`);
  if (color && color !== '블랙' && color !== '블랙앤그레이') pro.push('컬러 리터치 조건 · 패치 테스트 여부 사전 고지');

  const text = toText({ r, style: styleInfo, motifs, subject, color: colorInfo, place: placeInfo, plan, pro: false });
  return { title: '타투 상담 카드', to: '타투이스트', genre: r.genre?.level !== 'low' ? r.genre?.name : null, motifs, subject, plan, place: placeInfo, style: styleInfo, color: colorInfo, ask: ASK, prep: PREP, after: AFTER, pro, text };
}

function toText({ r, style, motifs, subject, color, place, plan }) {
  const L = ['[타투 상담 카드]'];
  if (r.genre?.name) L.push(`원하는 스타일: ${r.genre.name}`);
  if (style) L.push(`장르: ${style.name}${style.sure ? '' : ' (추정)'}`);
  if (subject || motifs.length) L.push(`도안: ${[subject, ...motifs].filter(Boolean).join(' · ')}`);
  if (color.name) L.push(`컬러: ${color.name}`);
  if (place) L.push(`부위: ${place.name}${place.sure ? '' : ' (추정)'} · 통증 참고 ${place.pain}/5 (${place.painText})`);
  L.push(`크기 · 시간: ${plan.size || '-'} (${plan.cm}) · 예상 ${plan.time} · ${plan.sessions}`);
  L.push('', '미리 알아 둘 것');
  for (const p of style?.points || []) L.push(`- ${p}`);
  for (const p of place?.points || []) L.push(`- ${p}`);
  for (const p of color.points) L.push(`- ${p}`);
  if (color.skinNote) L.push(`- ${color.skinNote}`);
  L.push('', '상담 때 물어볼 것', ...ASK.map((x) => `- ${x}`));
  L.push('', '시술 전 준비', ...PREP.map((x) => `- ${x}`));
  L.push('', '애프터케어', ...AFTER.map((x) => `- ${x}`));
  L.push('', '통증 · 시간 · 회차는 일반적인 참고 범위예요. 실제 시술은 타투이스트와 상담해 정해 주세요. (AI 생성 · FINDE)');
  return L.join('\n');
}
