export function accessoryAdvice(shape, t = {}) {
  const g = { ...(G[shape] || G.oval) }, e = { ...(E[shape] || E.oval) };
  const gNotes = [], eNotes = [];
  const cheekPop = -((t.foreheadW || 0) + (t.jawW || 0)) / 2;
  if (t.foreheadW >= 0.8) gNotes.push('이마가 넓은 편이라 프레임 너비는 광대 너비와 같거나 살짝 넓게.');
  if (t.foreheadW <= -0.8) gNotes.push('이마가 좁은 편이라 상단이 두꺼운 프레임은 피하고 얇은 테가 좋아요.');
  if (t.eyeWide <= -0.8) gNotes.push('미간이 좁은 편이라 브릿지가 밝은색이거나 투명한, 얇은 프레임이 눈 사이를 넓어 보이게 해요.');
  if (t.eyeWide >= 0.8) gNotes.push('미간이 넓은 편이라 브릿지가 진한색이고 짧은 프레임이 좋아요.');
  if (t.noseW >= 0.8) gNotes.push('콧볼이 넓은 편이라 브릿지가 코 위쪽에 걸리는 높은 브릿지 프레임이 좋아요.');
  if (t.long >= 0.8 && shape !== 'long') gNotes.push('얼굴이 긴 편이라 렌즈 세로가 깊은 프레임이 길이를 나눠 줘요.');
  if (cheekPop >= 0.8 && shape !== 'diamond') gNotes.push('광대가 넓은 편이라 위쪽에 포인트가 있는 프레임(캣아이 · 브로우라인)이 시선을 올려 줘요.');
  if (t.ears === 'out') eNotes.push('귀가 옆으로 보이는 편이라 큰 후프보다 귀에 붙는 스터드나 아래로 떨어지는 드롭이 좋아요.');
  if (t.jawW >= 0.8 && shape !== 'square') eNotes.push('턱이 넓은 편이라 턱선 아래까지 내려오는 길이의 드롭이 턱 폭을 덜 보이게 해요.');
  if (t.chinW <= -0.8 && shape !== 'heart') eNotes.push('턱끝이 뾰족한 편이라 아래가 넓은 티어드롭이 균형을 잡아 줘요.');
  if (t.long <= -0.8 && shape !== 'round') eNotes.push('얼굴이 짧은 편이라 세로로 긴 드롭이 길어 보이게 해요.');
  const pack = (x, notes) => ({ good: x.good.map((n) => ({ name: n, icon: ICON[n] || '' })), avoid: x.avoid, tip: [x.tip, ...notes].join(' ') });
  return { glasses: pack(g, gNotes), earrings: pack(e, eNotes) };
}
